export const { I18nProvider, useI18n, translate } = createI18n<Key>({ "pt-BR": ptBR, en, "zh-CN": zhCN });
export type TKey = Key;

/** Free text used in resource definitions: plain PT-BR string, or per-locale object. */
export type Text = string | { "pt-BR": string; en?: string; "zh-CN"?: string };

export function useText() {
  const { locale } = useI18n();
  return useCallback(
    (x: Text | undefined): string => {
      if (x === undefined) return "";
      if (typeof x === "string") return x;
      return x[locale] ?? x["pt-BR"];
    },
    [locale],
  );
}
